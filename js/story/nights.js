  DL.playNight = async function (s, io) {
    const N = NIGHTS.find((n) => n.sem === s.sem);
    if (!N || !io.night) return;
    const v = io.night;
    const line = (l) => v.say(l[0], DL.fmt(l[1], s));
    await v.start({ label: (DL.SEMESTERS[s.sem] || {}).label || "", bed: s.flags.bed }, s);
    for (const l of N.open) await line(l);
    const tops = N.topics.filter((t) => DL.test(t.if, s));
    const k = await v.ask(DL.fmt(N.q, s), tops.map((t) => DL.fmt(t.t, s)));
    const T = tops[k] || tops[0];
    if (T.id === "letter") s.flags.letterFound = true;
    s.flags.nights = (s.flags.nights || 0) + 1;
    s.flags.nightTopics = (s.flags.nightTopics || []).concat(DL.fmt(T.t, s).replace(/^[“「]|[”」]$/g, ""));
    for (const l of T.lines) await line(l);
    if (T.ask) {
      const opts = T.ask.options.filter((o) => DL.test(o.if, s));
      const j = await v.ask(DL.fmt(T.ask.q, s), opts.map((o) => DL.fmt(o.t, s)));
      const o = opts[j] || opts[0];
      if (o.set) Object.assign(s.flags, o.set);
      // 卧谈会是“每学期都有”的东西，关系加成要克制，避免把结局整体推向圆满
      if (o.fx) {
        const fx = Object.assign({}, o.fx);
        // 对全宿舍说的话只加心情；对某一个人说的话，才算进那个人的关系里
        if (fx.rel) { const ks = Object.keys(o.fx.rel); fx.rel = {}; if (ks.length === 1) fx.rel[ks[0]] = Math.max(1, Math.round(o.fx.rel[ks[0]] * 0.4)); }
        io.toast(DL.applyFx(s, fx), s);
      }
      for (const l of o.reply || []) await line(l);
    }
    await v.end(DL.fmt(N.close, s));
  };
